import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const registryPath = path.join(packageRoot, "schema/cache-metrics.json");
const pricingSchemaPath = "schema/cache-metrics.generated.ts";
const identifier = /^[a-z][a-z0-9_]*$/;

export function parseCacheMetricGroups(groups) {
  if (!Array.isArray(groups) || groups.length === 0) {
    throw new Error("Cache metric groups must be a nonempty array");
  }
  const ids = new Set();
  const ttls = new Set();
  const metricNames = new Set();
  const rateNames = new Set();
  const metrics = [];
  for (const [group, definition] of groups.entries()) {
    if (
      !isObject(definition) ||
      typeof definition.id !== "string" ||
      !identifier.test(definition.id) ||
      ids.has(definition.id) ||
      !Array.isArray(definition.metrics) ||
      definition.metrics.length === 0
    ) {
      throw new Error(`Invalid cache metric group at index ${group}`);
    }
    ids.add(definition.id);
    for (const [index, entry] of definition.metrics.entries()) {
      if (!isObject(entry)) {
        throw new Error(
          `Invalid cache metric at index ${index} of group ${definition.id}`,
        );
      }
      const { ttl, metric, rate_key: rate } = entry;
      if (
        typeof ttl !== "string" ||
        !/^[1-9][0-9]*[mh]$/.test(ttl) ||
        ttls.has(ttl)
      ) {
        throw new Error(`Invalid or duplicate cache TTL: ${ttl}`);
      }
      if (
        typeof metric !== "string" ||
        !identifier.test(metric) ||
        metricNames.has(metric)
      ) {
        throw new Error(`Invalid or duplicate cache metric name: ${metric}`);
      }
      if (
        typeof rate !== "string" ||
        !identifier.test(rate) ||
        rateNames.has(rate)
      ) {
        throw new Error(`Invalid or duplicate cache rate key: ${rate}`);
      }
      if (
        metric !== `prompt_cache_creation_${ttl}_tokens` ||
        rate !== `input_cache_write_${ttl}_cost_per_mil_tokens`
      ) {
        throw new Error(
          `Cache metric ${metric} and rate key ${rate} do not match TTL ${ttl}`,
        );
      }
      ttls.add(ttl);
      metricNames.add(metric);
      rateNames.add(rate);
      metrics.push({ index: metrics.length, group, ttl, metric, rate });
    }
  }
  return { groups, metrics };
}

function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function loadCacheMetrics() {
  return parseCacheMetricGroups(
    JSON.parse(fs.readFileSync(registryPath, "utf8")),
  );
}

export function renderPricingSchema({ metrics }) {
  return `// Generated by scripts/cache_metrics.mjs from schema/cache-metrics.json. Do not edit.

import { z } from "zod";

export const cacheWritePricingShape = {
${metrics.map(({ rate }) => `  ${rate}: z.number().nullish(),`).join("\n")}
};

export const cacheWriteRateKeys = [
${metrics.map(({ rate }) => `  "${rate}",`).join("\n")}
] as const;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const destination = path.join(packageRoot, pricingSchemaPath);
  const contents = renderPricingSchema(loadCacheMetrics());
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(destination) ||
      fs.readFileSync(destination, "utf8") !== contents
    ) {
      console.error(
        `${pricingSchemaPath} is out of date; run pnpm generate:cache-metrics`,
      );
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(destination, contents);
    console.log(`Wrote ${pricingSchemaPath}`);
  }
}
