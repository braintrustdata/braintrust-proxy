import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const registryPath = path.join(packageRoot, "schema/cache-metrics.json");
const pricingSchemaPath = "schema/cache-metrics.generated.ts";
const cacheMetricsPath = "schema/cache-metric-definitions.generated.ts";
const identifier = /^[a-z][a-z0-9_]*$/;

export function parseCacheMetricGroups(groups) {
  if (!Array.isArray(groups) || groups.length === 0) {
    throw new Error("Cache metric groups must be a nonempty array");
  }
  const ids = new Set();
  const ttls = new Set();
  const metricNames = new Set();
  const rateNames = new Set();
  const metrics = [];
  for (const [group, definition] of groups.entries()) {
    if (
      !isObject(definition) ||
      typeof definition.id !== "string" ||
      !identifier.test(definition.id) ||
      ids.has(definition.id) ||
      !Array.isArray(definition.metrics) ||
      definition.metrics.length === 0
    ) {
      throw new Error(`Invalid cache metric group at index ${group}`);
    }
    ids.add(definition.id);
    for (const [index, entry] of definition.metrics.entries()) {
      if (!isObject(entry)) {
        throw new Error(
          `Invalid cache metric at index ${index} of group ${definition.id}`,
        );
      }
      const { ttl, metric, rate_key: rate } = entry;
      if (
        typeof ttl !== "string" ||
        !/^[1-9][0-9]*[mh]$/.test(ttl) ||
        ttls.has(ttl)
      ) {
        throw new Error(`Invalid or duplicate cache TTL: ${ttl}`);
      }
      if (
        typeof metric !== "string" ||
        !identifier.test(metric) ||
        metricNames.has(metric)
      ) {
        throw new Error(`Invalid or duplicate cache metric name: ${metric}`);
      }
      if (
        typeof rate !== "string" ||
        !identifier.test(rate) ||
        rateNames.has(rate)
      ) {
        throw new Error(`Invalid or duplicate cache rate key: ${rate}`);
      }
      if (
        metric !== `prompt_cache_creation_${ttl}_tokens` ||
        rate !== `input_cache_write_${ttl}_cost_per_mil_tokens`
      ) {
        throw new Error(
          `Cache metric ${metric} and rate key ${rate} do not match TTL ${ttl}`,
        );
      }
      ttls.add(ttl);
      metricNames.add(metric);
      rateNames.add(rate);
      metrics.push({ index: metrics.length, group, ttl, metric, rate });
    }
  }
  return { groups, metrics };
}

function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function loadCacheMetrics() {
  return parseCacheMetricGroups(
    JSON.parse(fs.readFileSync(registryPath, "utf8")),
  );
}

export function renderPricingSchema({ metrics }) {
  return `// Generated by scripts/cache_metrics.mjs from schema/cache-metrics.json. Do not edit.

import { z } from "zod";

export const cacheWritePricingShape = {
${metrics.map(({ rate }) => `  ${rate}: z.number().nullish(),`).join("\n")}
};

export const cacheWriteRateKeys = [
${metrics.map(({ rate }) => `  "${rate}",`).join("\n")}
] as const;
`;
}

export function renderCacheMetrics({ groups, metrics: registryMetrics }) {
  const metrics = registryMetrics.map(
    ({ index, group, ttl, metric, rate }) => ({
      index,
      group,
      metric,
      rate,
      usage: `promptCacheCreation${ttl}Tokens`,
      cost: `promptCacheCreation${ttl}TokensCost`,
      title: `Prompt cache creation (${ttl}) tokens`,
    }),
  );
  return `// Generated by scripts/cache_metrics.mjs from schema/cache-metrics.json. Do not edit.

function defineMetrics<const T>(value: T): T {
  return value;
}

export const cacheWriteMetrics = defineMetrics([
${metrics
  .map(
    (metric) => `  {
${Object.entries(metric)
  .map(([key, value]) => `    ${key}: ${JSON.stringify(value)},`)
  .join("\n")}
  },`,
  )
  .join("\n")}
]);

export const cacheWriteMetricGroups = defineMetrics([
${groups
  .map(
    (group, index) =>
      `  { id: ${JSON.stringify(group.id)}, metrics: [${metrics
        .filter((metric) => metric.group === index)
        .map((metric) => `cacheWriteMetrics[${metric.index}]`)
        .join(", ")}] },`,
  )
  .join("\n")}
]);

export const cacheWriteMetricNames = cacheWriteMetrics.map(
  ({ metric }) => metric,
);

export type CacheWriteMetricName = (typeof cacheWriteMetrics)[number]["metric"];
export type CacheWriteRateName = (typeof cacheWriteMetrics)[number]["rate"];
export type CacheWriteUsageName = (typeof cacheWriteMetrics)[number]["usage"];

export function mapCacheWriteMetrics<T>(
  get: (metric: CacheWriteMetricName) => T,
): Record<CacheWriteMetricName, T> {
  return {
${metrics.map(({ metric }) => `    ${metric}: get(${JSON.stringify(metric)}),`).join("\n")}
  };
}

export function mapCacheWriteUsage<T>(
  get: (metric: CacheWriteMetricName) => T,
): Record<CacheWriteUsageName, T> {
  return {
${metrics.map(({ usage, metric }) => `    ${usage}: get(${JSON.stringify(metric)}),`).join("\n")}
  };
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const registry = loadCacheMetrics();
  const outputs = [
    [pricingSchemaPath, renderPricingSchema(registry)],
    [cacheMetricsPath, renderCacheMetrics(registry)],
  ];
  for (const [relativePath, contents] of outputs) {
    const destination = path.join(packageRoot, relativePath);
    if (process.argv.includes("--check")) {
      if (
        !fs.existsSync(destination) ||
        fs.readFileSync(destination, "utf8") !== contents
      ) {
        console.error(
          `${relativePath} is out of date; run pnpm generate:cache-metrics`,
        );
        process.exitCode = 1;
      }
    } else {
      fs.writeFileSync(destination, contents);
      console.log(`Wrote ${relativePath}`);
    }
  }
}
